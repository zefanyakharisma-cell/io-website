// Fetches the Wikimedia Commons photos listed in scripts/web-photos.json, checks each licence,
// writes responsive WebP files to public/images/web/<group>/ and the credits to
// src/content/web-photos.generated.ts.
// Usage: NODE_USE_ENV_PROXY=1 node scripts/fetch-web-photos.mjs   (the env var only behind a proxy)
import sharp from "sharp";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const manifest = JSON.parse(fs.readFileSync(path.join(root, "scripts/web-photos.json"), "utf8"));
const UA = "PCU-IO-website-build/1.0 (https://github.com/zefanyakharisma-cell/io-website)";
// Free licences only: anything else (fair use, non-free logos) stops the build.
const FREE = /^(CC0|Public domain|PD[- ]|CC BY [0-9.]+|CC BY-SA [0-9.]+)/i;
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "web-photos-"));
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const strip = (h = "") => h.replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();

// Commons rate-limits shared addresses; honour Retry-After and go slowly.
async function get(url) {
  for (let i = 0; i < 6; i++) {
    const r = await fetch(url, { headers: { "User-Agent": UA } });
    if (r.ok) return r;
    await sleep((Number(r.headers.get("retry-after")) || 10) * 1000 + 1000);
  }
  throw new Error(`Failed: ${url}`);
}

const out = {};
for (const [group, items] of Object.entries(manifest)) {
  const dir = path.join(root, "public/images/web", group);
  fs.mkdirSync(dir, { recursive: true });
  out[group] = {};
  for (const [name, [title, alt]] of Object.entries(items)) {
    const q = new URLSearchParams({ action: "query", format: "json", titles: title, prop: "imageinfo", iiprop: "url|extmetadata|size", iiurlwidth: "1600" });
    const page = Object.values((await (await get(`https://commons.wikimedia.org/w/api.php?${q}`)).json()).query.pages)[0];
    const info = page.imageinfo?.[0];
    if (!info) throw new Error(`Not found on Commons: ${title}`);
    const meta = info.extmetadata;
    const license = strip(meta.LicenseShortName?.value);
    if (!FREE.test(license)) throw new Error(`${title}: licence "${license}" is not on the allow-list`);
    const file = path.join(tmp, `${group}-${name}`);
    fs.writeFileSync(file, Buffer.from(await (await get(info.thumburl)).arrayBuffer()));
    const { width } = await sharp(file).metadata();
    const widths = [...new Set([Math.min(width, 1600), Math.min(width, 800)])];
    for (const w of widths) {
      await sharp(file).rotate().resize({ width: w, withoutEnlargement: true }).webp({ quality: 78 }).toFile(path.join(dir, `${name}-${w}.webp`));
    }
    const { height: h0 } = await sharp(path.join(dir, `${name}-${widths[0]}.webp`)).metadata();
    out[group][name] = {
      src: `/images/web/${group}/${name}-${widths[0]}.webp`,
      small: `/images/web/${group}/${name}-${widths.at(-1)}.webp`,
      width: widths[0],
      height: h0,
      alt,
      credit: {
        author: strip(meta.Artist?.value) || "Unknown",
        license,
        licenseUrl: meta.LicenseUrl?.value ?? "",
        source: info.descriptionurl,
      },
    };
    console.log(`${group}/${name}: ${license} · ${out[group][name].credit.author}`);
    await sleep(1500);
  }
}
fs.rmSync(tmp, { recursive: true, force: true });

const ts = `// Generated by scripts/fetch-web-photos.mjs from scripts/web-photos.json. Do not edit by hand.
export type Credit = { author: string; license: string; licenseUrl: string; source: string };
export type WebPhoto = { src: string; small: string; width: number; height: number; alt: string; credit: Credit };
export const webPhotos = ${JSON.stringify(out, null, 2)} as const satisfies Record<string, Record<string, WebPhoto>>;
`;
fs.writeFileSync(path.join(root, "src/content/web-photos.generated.ts"), ts);

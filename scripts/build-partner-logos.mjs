// Converts national partner logos (one file per partner, named after the partner) into WebP
// files in public/images/logos/national/ and writes src/content/national-partners.generated.ts.
// Usage: node scripts/build-partner-logos.mjs <folder-with-logo-files>
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";

const src = process.argv[2];
if (!src) throw new Error("Pass the folder of logo files");
const root = path.resolve(import.meta.dirname, "..");
const dir = path.join(root, "public/images/logos/national");
fs.rmSync(dir, { recursive: true, force: true });
fs.mkdirSync(dir, { recursive: true });

const slug = (s) => s.normalize("NFKD").replace(/[^\w\s-]/g, "").trim().toLowerCase().replace(/[\s_]+/g, "-").replace(/-+/g, "-").slice(0, 60);
const clean = (s) => s.replace(/\s+logo$/i, "").replace(/\.+$/, ".").replace(/\s+/g, " ").trim();

/** Rough category from the partner's name. */
function kind(name) {
  if (/monash|universit/i.test(name)) return "University";
  if (/^(RS|RSUD|Rumah Sakit)\b|Hospital/i.test(name)) return "Healthcare";
  if (/Pemerintah|Kementerian|Kementrian|Sekretariat|Komisi Nasional|Tentara|Badan Pengembangan|Badan Arsip|Bank Pembangunan Daerah/i.test(name)) return "Government";
  if (/^PT\b|Group|Hotel|Sheraton|Marriott|Hilton|RSM|Grant Thornton/i.test(name)) return "Industry";
  return "Organisation";
}

const out = [];
for (const file of fs.readdirSync(src).sort((a, b) => a.localeCompare(b))) {
  const name = clean(path.parse(file).name);
  const base = slug(name);
  const input = path.join(src, file);
  const isSvg = file.toLowerCase().endsWith(".svg");
  // Trim flat margins so every logo fills its tile the same way; SVGs are rasterised large first.
  const buf = await sharp(input, { density: isSvg ? 150 : 72, limitInputPixels: false }).flatten({ background: "#ffffff" }).trim({ threshold: 12 }).toBuffer();
  const img = sharp(buf).resize({ width: 400, height: 220, fit: "inside", withoutEnlargement: true });
  const { data, info } = await img.webp({ quality: 88 }).toBuffer({ resolveWithObject: true });
  fs.writeFileSync(path.join(dir, `${base}.webp`), data);
  out.push({ name, kind: kind(name), logo: { src: `/images/logos/national/${base}.webp`, alt: `${name} logo`, width: info.width, height: info.height } });
  console.log(`${base}.webp ${info.width}x${info.height} ${kind(name)}`);
}

const ts = `// Generated by scripts/build-partner-logos.mjs — do not edit.\nexport type NationalKind = "University" | "Industry" | "Government" | "Healthcare" | "Organisation";\n\nexport const nationalPartners: { name: string; kind: NationalKind; logo: { src: string; alt: string; width: number; height: number } }[] = ${JSON.stringify(out, null, 2)};\n`;
fs.writeFileSync(path.join(root, "src/content/national-partners.generated.ts"), ts);
console.log(`${out.length} logos`);

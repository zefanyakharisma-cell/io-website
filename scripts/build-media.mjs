// Converts deck images into responsive WebP files and writes src/content/media.generated.ts.
// Usage: node scripts/build-media.mjs <path-to-extracted-ppt/media>
import sharp from "sharp";
import fs from "node:fs";
import path from "node:path";

const src = process.argv[2];
if (!src) throw new Error("Pass the extracted ppt/media folder");
const root = path.resolve(import.meta.dirname, "..");
const manifest = JSON.parse(fs.readFileSync(path.join(root, "scripts/media-manifest.json"), "utf8"));
const out = {};

for (const [group, items] of Object.entries(manifest)) {
  const dir = path.join(root, "public/images", group);
  fs.mkdirSync(dir, { recursive: true });
  out[group] = {};
  for (const [name, [file, alt]] of Object.entries(items)) {
    const input = sharp(path.join(src, file));
    const { width, height } = await input.metadata();
    const isGraphic = group === "logos" || group === "brand";
    const widths = isGraphic ? [Math.min(width, 640)] : [...new Set([Math.min(width, 1600), Math.min(width, 800)])];
    for (const w of widths) {
      await sharp(path.join(src, file))
        .resize({ width: w, withoutEnlargement: true })
        .webp({ quality: isGraphic ? 90 : 78, alphaQuality: 100 })
        .toFile(path.join(dir, `${name}-${w}.webp`));
    }
    out[group][name] = {
      src: `/images/${group}/${name}-${widths[0]}.webp`,
      small: `/images/${group}/${name}-${widths.at(-1)}.webp`,
      width: widths[0],
      height: Math.round((height / width) * widths[0]),
      alt,
    };
  }
}

const ts = `// Generated by scripts/build-media.mjs from scripts/media-manifest.json. Do not edit by hand.
export type Media = { src: string; small: string; width: number; height: number; alt: string };
export const media = ${JSON.stringify(out, null, 2)} as const satisfies Record<string, Record<string, Media>>;
`;
fs.writeFileSync(path.join(root, "src/content/media.generated.ts"), ts);
console.log("groups:", Object.keys(out).map((g) => `${g}=${Object.keys(out[g]).length}`).join(" "));
